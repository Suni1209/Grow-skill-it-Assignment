package day1;
public class Program3DatatypeExample {
	public static void main(String[] args) {
		//boolean takes 1 bit
		boolean result=false;
		System.out.println(result);
		
		//byte takes 1 byte=8bits
		//-128 to 127
		byte ans=-128;
		System.out.println(ans);
		
		//short takes 2 bytes
		//-32000 to 32000
		short data=-32000;
		System.out.println(data);
		
		//char takes 2 bytes
		char alpha='A';
		System.out.println(alpha);
		
		//8 bytes
		long phoneNumber=9876543210L;
		System.out.println(phoneNumber);
		
		//foat 4 bytes
		//7 floating points
		float marks3=9.12345678F;
		System.out.println(marks3);
		
		float marks4=91.235678F;
		System.out.println(marks4);
		
		float marks5=912.345678F;
		System.out.println(marks5);
		
		float marks6=9123.45678F;
		System.out.println(marks6);
		
		//8 bytes
		double data3=9.123456789012345;
		System.out.println(data3);
		
		
		
	}

}
